#!/usr/bin/env python3
"""Writes assets/bg/title.pixels: Lanternfall's title screen, 160x144.

  python3 -I tools/title.py       (from anywhere; byte-identical every run)

A lantern hangs in the dark, its light falling off in dithered rings, above
the name in the font's glyphs at twice their size. Indices 0-3 are the ember
palette's entries, lightest first (assets/palettes.txt).
"""

import math
import os
import sys

sys.dont_write_bytecode = True     # no __pycache__ in the repo
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from font import GLYPHS  # noqa: E402  (tools/font.py: the 5x7 glyphs)

W, H = 160, 144
BAYER = [[0, 8, 2, 10], [12, 4, 14, 6], [3, 11, 1, 9], [15, 7, 13, 5]]


def text(img, s, x, y, scale, color, advance):
    for ch in s:
        for gy, row in enumerate(GLYPHS[ch]):
            for gx, c in enumerate(row):
                if c == "#":
                    for dy in range(scale):
                        for dx in range(scale):
                            img[y + gy * scale + dy][x + gx * scale + dx] = color
        x += advance


def centered(s, advance, glyph_w):
    return (W - (advance * (len(s) - 1) + glyph_w)) // 2


def main():
    img = [[3] * W for _ in range(H)]

    # The glow: light falling off from the lantern's flame, ordered-dithered
    # into shades 3 (dark) to 2, so it reads as light on the DMG too.
    cx, cy = 80, 28
    for y in range(H):
        for x in range(W):
            d = math.hypot(x - cx, (y - cy) * 1.15)
            if d < 46:
                level = (46 - d) / 46 * 16      # 0..16
                if BAYER[y % 4][x % 4] < level * 0.7:
                    img[y][x] = 2

    # The lantern: hook, cap, cage and flame.
    lantern = [
        "......3333......",
        ".....3....3.....",
        ".....3....3.....",
        "......3333......",
        ".......33.......",
        "....33333333....",
        "...3222222223...",
        "..333333333333..",
        "..3.3..11..3.3..",
        "..3.3.1001.3.3..",
        "..3.3.1001.3.3..",
        "..3.31000013.3..",
        "..3.31000013.3..",
        "..3.3.1001.3.3..",
        "..3.3..11..3.3..",
        "..333333333333..",
        "...3222222223...",
        "....33333333....",
        "......3223......",
        ".......33.......",
    ]
    lx, ly = cx - 16, 8                 # drawn at twice size
    for y, row in enumerate(lantern):
        for x, c in enumerate(row):
            if c != ".":
                for dy in range(2):
                    for dx in range(2):
                        img[ly + 2 * y + dy][lx + 2 * x + dx] = int(c)
    # A chain up to the top of the screen.
    for y in range(0, ly):
        if y % 3 != 2:
            img[y][cx - 1] = 1 if y % 3 == 0 else 2

    name = "LANTERNFALL"
    text(img, name, centered(name, 13, 10) + 2, 70, 2, 3, 13)   # shadow
    text(img, name, centered(name, 13, 10), 68, 2, 0, 13)
    sub = "A DESCENT OF FIVE FLOORS"
    text(img, sub, centered(sub, 6, 5), 96, 1, 1, 6)
    start = "PRESS START"
    text(img, start, centered(start, 6, 5), 120, 1, 0, 6)

    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "assets", "bg", "title.pixels")
    os.makedirs(os.path.dirname(out), exist_ok=True)
    lines = ["format gbcli-pixels 1",
             "# Generated by tools/title.py; edit that, not this.",
             f"size {W} {H}",
             "color 0 ember 0", "color 1 ember 1", "color 2 ember 2", "color 3 ember 3",
             "",
             "rows 0 0"]
    lines += ["".join(str(c) for c in row) for row in img]
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
