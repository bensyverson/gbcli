#!/usr/bin/env python3
"""Generates crates/font/src/marks/table.rs: gbcli's mark table.

The table is every precomposed letter in Latin-1 Supplement (U+00C0-U+00FF)
and Latin Extended-A (U+0100-U+017F) whose canonical decomposition is one
base character and one combining mark, plus the singletons whose canonical
form is one of those letters (U+212B ANGSTROM SIGN is A with a ring).
The font reader refuses a decomposed key the table knows, naming its
precomposed form (design 2026-11-09-pixel-fonts-design.md, Ben's ruling 3);
composing a missing letter from its base and mark builds on the same table.

Python's unicodedata is the reference, so gbcli needs no normalization
dependency at run time. Run from anywhere:

    python3 -I scripts/fonts/gen_marks.py          # rewrite table.rs
    python3 -I scripts/fonts/gen_marks.py --check  # fail if table.rs is stale
"""

import sys
import unicodedata
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / "crates/font/src/marks/table.rs"
RANGES = [(0x00C0, 0x00FF), (0x0100, 0x017F)]


def precomposed():
    for lo, hi in RANGES:
        for cp in range(lo, hi + 1):
            d = unicodedata.decomposition(chr(cp))
            if not d or d.startswith("<"):
                continue
            parts = [int(p, 16) for p in d.split()]
            if len(parts) == 2 and unicodedata.combining(chr(parts[1])):
                yield parts[0], parts[1], cp


def singletons(letters):
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<") or " " in d:
            continue
        target = int(d, 16)
        if target in letters and cp not in letters:
            yield cp, target


def render():
    rows = list(precomposed())
    letters = {cp for _, _, cp in rows}
    lines = [
        "// Generated by scripts/fonts/gen_marks.py from Python's unicodedata "
        f"{unicodedata.unidata_version}; do not edit.",
        "",
        "/// (base, combining mark, precomposed letter), by letter.",
        "pub(crate) const DECOMPOSED: &[(char, char, char)] = &[",
    ]
    for base, mark, cp in rows:
        lines.append(f"    ('\\u{{{base:04X}}}', '\\u{{{mark:04X}}}', '\\u{{{cp:04X}}}'),")
    lines.append("];")
    lines.append("")
    lines.append("/// (singleton, the letter it is canonically).")
    pairs = [f"('\\u{{{cp:04X}}}', '\\u{{{t:04X}}}')" for cp, t in singletons(letters)]
    one_line = "pub(crate) const SINGLETONS: &[(char, char)] = &[" + ", ".join(pairs) + "];"
    if len(one_line) <= 100:
        # As rustfmt writes a short array, so `cargo fmt` leaves the file be.
        lines.append(one_line)
    else:
        lines.append("pub(crate) const SINGLETONS: &[(char, char)] = &[")
        lines.extend(f"    {p}," for p in pairs)
        lines.append("];")
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text() != text:
            sys.exit(f"{OUTPUT} is stale: run scripts/fonts/gen_marks.py")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)


if __name__ == "__main__":
    main()
