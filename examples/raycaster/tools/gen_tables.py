#!/usr/bin/env python3
"""Writes src/tables.asm from raymath.py's tables.

Run from anywhere: python3 tools/gen_tables.py [--check]
--check exits 1 if src/tables.asm differs from what it would write.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import raymath as rm  # noqa: E402

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "tables.asm")


def rows(values, fmt, per=16):
    lines = []
    for i in range(0, len(values), per):
        lines.append("\tdb " + ", ".join(fmt(v) for v in values[i:i + per]))
    return lines


def hexb(v):
    return "$%02X" % (v & 0xFF)


def generate():
    out = [
        "; Generated by tools/gen_tables.py from tools/raymath.py; do not edit.",
        "; The host reference renderer (tools/reference.py) uses the same tables.",
        "",
        "SECTION \"Delta table lo\", ROM0, ALIGN[8]",
        "; |1/cos(a)| in 8.8 for a = 0..1023, low bytes then high bytes.",
        "DeltaLo::",
    ]
    out += rows([d & 0xFF for d in rm.DELTA], hexb)
    out += ["", "SECTION \"Delta table hi\", ROM0, ALIGN[8]", "DeltaHi::"]
    out += rows([d >> 8 for d in rm.DELTA], hexb)
    out += [
        "",
        "SECTION \"Half heights\", ROM0, ALIGN[8]",
        "; Wall half height in pixels by perpendicular distance >> 3.",
        "HalfHeight::",
    ]
    out += rows(rm.HH, lambda v: "%d" % v)
    out += [
        "",
        "SECTION \"Move table\", ROM0, ALIGN[8]",
        "; cos(a) * %d as a signed byte; sin(a) is entry (a - 256) & 1023." % rm.MOVE_SPEED,
        "MoveTab::",
    ]
    out += rows(rm.MOVE, hexb)
    out += [
        "",
        "SECTION \"Column tables\", ROM0, ALIGN[8]",
        "; Each ray's angle offset from the view direction (signed 16-bit).",
        "ColOffLo::",
    ]
    out += rows([o & 0xFF for o in rm.COL_OFF], hexb)
    out += ["ColOffHi::"]
    out += rows([(o >> 8) & 0xFF for o in rm.COL_OFF], hexb)
    out += ["; cos of each ray's offset in 0.8, capped at 255.", "CosOff::"]
    out += rows(rm.COS_OFF, lambda v: "%d" % v)
    sq = [x * x // 4 for x in range(512)]
    out += [
        "",
        "SECTION \"Quarter squares\", ROM0, ALIGN[8]",
        "; floor(x * x / 4) for x = 0..511, low bytes then high bytes:",
        "; a * b = Sq(a + b) - Sq(|a - b|).",
        "SqLo::",
    ]
    out += rows([v & 0xFF for v in sq], hexb)
    out += ["SqHi::"]
    out += rows([v >> 8 for v in sq], hexb)
    shades = []
    for cell in range(4):
        for side in range(2):
            shades.append(rm.CELL_SHADES.get(cell, (0, 0))[side])
    out += [
        "",
        "SECTION \"Cell shades\", ROM0, ALIGN[3]",
        "; Each map cell's face shade, x side then y side, for cells 0-3.",
        "CellShade::",
    ]
    out += rows(shades, lambda v: "%d" % v)
    pats = rm.wall_patterns()
    out += [
        "",
        "SECTION \"Wall tile tables\", ROM0, ALIGN[8]",
        "; The shared wall tile for a tile column's x-side pair bits (TILE_WALL0 + n).",
        "XToTile::",
    ]
    out += rows([0x90 + pats.index(x) if x in pats else 0 for x in range(256)], hexb)
    out += ["; Each shared wall tile's low-plane byte (its high plane is $FF).", "TileX::"]
    out += rows(pats, hexb)
    return "\n".join(out) + "\n"


def main():
    text = generate()
    path = os.path.normpath(OUT)
    if "--check" in sys.argv[1:]:
        with open(path) as f:
            if f.read() != text:
                print("stale: %s" % path)
                return 1
        print("ok: %s" % path)
        return 0
    with open(path, "w") as f:
        f.write(text)
    print("wrote %s" % path)
    return 0


if __name__ == "__main__":
    sys.exit(main())
