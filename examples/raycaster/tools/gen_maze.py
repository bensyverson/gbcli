#!/usr/bin/env python3
"""Writes src/maze.asm from the maze below, after checking it can be won.

  python3 tools/gen_maze.py [--check]

Legend: # stone, K a key (it floats over the floor: walk into its cell to
take it; the ROM turns the cell into floor and puts it on wKeyCell), D the
exit door (bump it holding every key), S the start (facing east), . open
floor. The border must be solid (stone or the door): rays stop only at walls.
--check exits 1 if src/maze.asm differs from what it would write.
"""

import os
import sys
from collections import deque

MAZE = """
################
#S....#.......K#
#.##.##.#####.##
#.#...#.#...#..#
#.#.#.#...#.##.#
#...#.#####.#..#
###.#.....#.#.##
#...#####.#.#..#
#.###...#.#.##.#
#.#K#.#.#......#
#.#.#.#.######.#
#...#.#......#.#
####..######.#.#
#K...##....#...#
#.##....##...#.D
################
"""

CELLS = {"#": 1, "K": 2, "D": 3, ".": 0, "S": 0}
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "src", "maze.asm")


def parse():
    rows = [r for r in MAZE.strip().splitlines()]
    assert len(rows) == 16 and all(len(r) == 16 for r in rows), "the maze is 16 x 16"
    start = None
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            assert ch in CELLS, "unknown cell %r at %d,%d" % (ch, x, y)
            if ch == "S":
                start = (x, y)
            if x in (0, 15) or y in (0, 15):
                assert ch in "#D", "the border must be solid at %d,%d" % (x, y)
    return rows, start


def check(rows, start):
    """Every key must be on floor reachable from the start, and the door must
    touch it."""
    seen = {start}
    todo = deque([start])
    while todo:
        x, y = todo.popleft()
        for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1)):
            n = (x + dx, y + dy)
            if rows[n[1]][n[0]] in ".SK" and n not in seen:
                seen.add(n)
                todo.append(n)
    for y, row in enumerate(rows):
        for x, ch in enumerate(row):
            if ch in "KD":
                near = [(x + dx, y + dy) for dx, dy in ((1, 0), (-1, 0), (0, 1), (0, -1))]
                assert any(n in seen for n in near), "%s at %d,%d can't be reached" % (ch, x, y)
    keys = sum(row.count("K") for row in rows)
    return keys, len(seen)


def generate(rows, start, keys):
    out = [
        "; Generated by tools/gen_maze.py; do not edit. The maze: 16 x 16 cells,",
        "; row by row. 0 floor, 1 stone, 2 a key (floor, once NewGame lists it),",
        "; 3 the exit door.",
        "",
        "SECTION \"Maze\", ROM0",
        "",
        "Maze::",
    ]
    for row in rows:
        out.append("\tdb " + ",".join(str(CELLS[c]) for c in row))
    out += [
        "",
        "DEF MAZE_KEYS EQU %d" % keys,
        "EXPORT MAZE_KEYS",
        "DEF MAZE_START_X EQU %d" % start[0],
        "EXPORT MAZE_START_X",
        "DEF MAZE_START_Y EQU %d" % start[1],
        "EXPORT MAZE_START_Y",
    ]
    return "\n".join(out) + "\n"


def main():
    rows, start = parse()
    keys, reach = check(rows, start)
    text = generate(rows, start, keys)
    path = os.path.normpath(OUT)
    if "--check" in sys.argv[1:]:
        with open(path) as f:
            ok = f.read() == text
        print(("ok: %s" if ok else "stale: %s") % path)
        return 0 if ok else 1
    with open(path, "w") as f:
        f.write(text)
    print("wrote %s keys=%d reachable_cells=%d" % (path, keys, reach))
    return 0


if __name__ == "__main__":
    sys.exit(main())
