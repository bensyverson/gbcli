ORDER = "ABCDEFGHIJKLMNOPQRSTUVWXYZ0123456789/!.:-"
BARS = 9  # oil bar tiles: 0-8 columns full


def tiles():
    out = []
    for ch in ORDER:
        rows = ["3" * 8 for _ in range(8)]
        for y, bits in enumerate(GLYPHS[ch]):
            rows[y] = "3" + "".join("0" if b == "1" else "3" for b in bits) + "33"
        out.append(("glyph %s" % ch, rows))
    for n in range(BARS):
        # Oil in shade 1 between two shade 2 rails, on black.
        fill = "1" * n + "3" * (8 - n)
        rows = ["33333333", "22222222", fill, fill, fill, fill, "22222222", "33333333"]
        out.append(("oil bar, %d columns full" % n, rows))
    return out


def pixels():
    ts = tiles()
    lines = [
        "format gbcli-pixels 1",
        "# Generated by tools/gen_font.py; do not edit. The HUD font, one tile per",
        "# glyph (%s), then the oil bar's tiles." % ORDER,
        "size %d 8" % (8 * len(ts)),
        "color 0 #ffffff",
        "color 1 #aaaaaa",
        "color 2 #555555",
        "color 3 #000000",
        "",
    ]
    for i, (name, rows) in enumerate(ts):
        lines.append("rows %d 0   # %s" % (8 * i, name))
        lines += rows
        lines.append("")
    return "\n".join(lines)


def charmap():
    lines = [
        "; Generated by tools/gen_font.py; do not edit. The HUD font's tile numbers.",
        "IF !DEF(CHARMAP_INC)",
        "DEF CHARMAP_INC EQU 1",
        "DEF FONT_BASE EQU $%02X" % FONT_BASE,
        "DEF FONT_BAR0 EQU $%02X" % (FONT_BASE + len(ORDER)),
        "DEF FONT_BARS EQU %d" % BARS,
        "\tCHARMAP \" \", $81  ; TILE_SOLID: the HUD is white on black",
    ]
    for i, ch in enumerate(ORDER):
        lines.append("\tCHARMAP \"%s\", $%02X" % (ch, FONT_BASE + i))
    lines.append("ENDC")
    return "\n".join(lines) + "\n"


def main():
    files = {
        os.path.join(ROOT, "assets", "tiles", "font.pixels"): pixels(),
        os.path.join(ROOT, "include", "charmap.inc"): charmap(),
    }
    check = "--check" in sys.argv[1:]
    bad = 0
    for path, text in files.items():
        if check:
            with open(path) as f:
                same = f.read() == text
            print(("ok: %s" if same else "stale: %s") % path)
            bad += not same
        else:
            os.makedirs(os.path.dirname(path), exist_ok=True)
            with open(path, "w") as f:
                f.write(text)
            print("wrote %s" % path)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
