"""Draws the clock's hand rotations: src/gen/clock.asm.

One 32x32 clock face (4x4 tiles) per hand position, CLOCK_STEPS of them
(from include/tuning.inc), the hand at 12 o'clock first and turning clockwise.
The game copies one into tile memory each time the hand moves.

    python3 tools/gen_clock.py          writes the file
    python3 tools/gen_clock.py --check  exits 1 if it is out of date
"""

import math
import sys

import tiles
import tuning

OUT = tuning.PROJECT / "src" / "gen" / "clock.asm"

SIZE = 32
CENTER = 15.5
RADIUS = 15.0
HAND = 11.5          # px from the center to the hand's tip
HAND_WIDTH = 0.9     # px either side of the hand's line

WALL, FACE, TICK, INK = 0, 1, 2, 3  # shades: the face is its own color, so it alone turns red


def face(step, steps):
    angle = 2 * math.pi * step / steps
    dx, dy = math.sin(angle), -math.cos(angle)
    img = []
    for y in range(SIZE):
        row = []
        for x in range(SIZE):
            px, py = x - CENTER, y - CENTER
            r = math.hypot(px, py)
            if r > RADIUS:
                row.append(WALL)
                continue
            if r > RADIUS - 1.5:
                row.append(INK)
                continue
            shade = FACE
            # Twelve tick marks just inside the rim.
            if r > RADIUS - 4:
                a = math.atan2(px, -py) % (2 * math.pi)
                nearest = round(a / (math.pi / 6)) * (math.pi / 6)
                if abs(a - nearest) * r < 0.9:
                    shade = TICK
            # The hand: points within HAND_WIDTH of the segment.
            along = px * dx + py * dy
            across = abs(px * dy - py * dx)
            if -1.0 <= along <= HAND and across <= HAND_WIDTH:
                shade = INK
            if r < 2.0:
                shade = INK
            row.append(shade)
        img.append(row)
    return img


def render(steps):
    lines = [
        "; Generated by tools/gen_clock.py from include/tuning.inc. Do not edit.",
        f"; {steps} clock faces, 16 tiles each (4x4, row by row), hand at",
        "; 12 o'clock first, turning clockwise.",
        'SECTION "Clock rotations", ROMX, ALIGN[8]   ; a face per 256-byte page',
        "ClockRotations::",
    ]
    for step in range(steps):
        lines.append(f"; step {step}")
        for tile in tiles.split(face(step, steps), 4, 4):
            lines.append("\tdb " + ",".join(f"${b:02X}" for b in tiles.encode(tile)))
    lines.append("ClockRotationsEnd::")
    return "\n".join(lines) + "\n"


def main():
    t = tuning.load()
    steps = t["CLOCK_STEPS"]
    if (t["ROUND_SECONDS"] * 60) % steps:
        sys.exit("CLOCK_STEPS must divide ROUND_SECONDS * 60")
    text = render(steps)
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit(f"{OUT.relative_to(tuning.PROJECT)} is out of date: run tools/gen_clock.py")
        return
    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(tuning.PROJECT)} steps={steps}")


if __name__ == "__main__":
    main()
