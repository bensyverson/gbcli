#!/usr/bin/env python3
"""Draws the title screen as pixel text: assets/bg/title.pixels (160 x 144).

  python3 tools/gen_title.py [--check]

The game's name in the HUD font at twice its size, a lantern, a corridor
receding to a door, and the prompt. Shades 0 (white) to 3 (black).
--check exits 1 if the file differs from what it would write.
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_font  # noqa: E402

ROOT = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
OUT = os.path.join(ROOT, "assets", "bg", "title.pixels")
W, H = 160, 144

LANTERN = [  # 24 x 34: 0 flame, 1 glass, 2 frame, 3 clear (the background)
    "3333333333222233333333333",
    "3333333332333323333333333",
    "3333333332333323333333333",
    "3333333333222233333333333",
    "3333333222222222233333333",
    "3333332222222222223333333",
    "3333322111111111122333333",
    "3333322111111111122333333",
    "3333322111110111122333333",
    "3333322111100011122333333",
    "3333322111100011122333333",
    "3333322111000001122333333",
    "3333322111000001122333333",
    "3333322111000001122333333",
    "3333322111100011122333333",
    "3333322111110111122333333",
    "3333322111112111122333333",
    "3333322111112111122333333",
    "3333322111111111122333333",
    "3333322111111111122333333",
    "3333332222222222223333333",
    "3333333222222222233333333",
    "3333333332222223333333333",
]


def canvas():
    return [[3] * W for _ in range(H)]


def text(c, s, x, y, scale=1, shade=0):
    for i, ch in enumerate(s):
        if ch == " ":
            continue
        for gy, bits in enumerate(gen_font.GLYPHS[ch]):
            for gx, b in enumerate(bits):
                if b == "1":
                    for dy in range(scale):
                        for dx in range(scale):
                            c[y + gy * scale + dy][x + i * 6 * scale + gx * scale + dx] = shade


def corridor(c):
    """A corridor to a door, below the lantern: walls narrowing to the middle."""
    top, bottom = 104, 143
    for y in range(top, bottom + 1):
        t = (y - top) / (bottom - top)
        half = int(14 + t * 66)
        for x in range(80 - half, 80 + half):
            edge = abs(x - 80) > half - 3
            # The floor: gray, dithered lighter toward the viewer.
            floor = 1 if (x + y) % 2 == 0 or t > 0.6 else 2
            c[y][x] = 2 if edge else floor
    for y in range(96, 104):  # the far door
        for x in range(74, 86):
            c[y][x] = 1 if 75 < x < 84 else 2


def draw():
    c = canvas()
    text(c, "LANTERN", 80 - 7 * 12 // 2 + 1, 10, scale=2)
    for y, row in enumerate(LANTERN):
        for x, v in enumerate(row):
            if v != "3":
                c[40 + y][68 + x] = int(v)
    corridor(c)
    text(c, "PRESS START", 80 - 11 * 6 // 2, 70)
    text(c, "FIND 3 KEYS", 80 - 11 * 6 // 2, 82, shade=1)
    return c


def pixels(c):
    lines = [
        "format gbcli-pixels 1",
        "# Generated by tools/gen_title.py; do not edit. The title screen.",
        "size %d %d" % (W, H),
        "color 0 #ffffff",
        "color 1 #aaaaaa",
        "color 2 #555555",
        "color 3 #000000",
        "",
        "rows 0 0",
    ]
    lines += ["".join(str(v) for v in row) for row in c]
    return "\n".join(lines) + "\n"


def main():
    text_out = pixels(draw())
    if "--check" in sys.argv[1:]:
        with open(OUT) as f:
            ok = f.read() == text_out
        print(("ok: %s" if ok else "stale: %s") % OUT)
        return 0 if ok else 1
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    with open(OUT, "w") as f:
        f.write(text_out)
    print("wrote %s" % OUT)
    return 0


if __name__ == "__main__":
    sys.exit(main())
