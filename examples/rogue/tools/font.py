KEYS = {" ": "space", "/": "slash", "!": "bang", ":": "colon", "-": "dash", ".": "dot", "'": "tick"}


def key(ch):
    return KEYS.get(ch, ("d" if ch.isdigit() else "c") + ch)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    out = os.path.join(here, "..", "assets", "tiles", "font.pixels")
    lines = ["format gbcli-pixels 1",
             "# Generated by tools/font.py; edit that, not this.",
             f"size {8 * len(CHARS)} 8",
             "color . stone 3",
             "color o stone 0",
             ""]
    for ch in CHARS:
        g = GLYPHS[ch]
        lines.append(f"tile {key(ch)}")
        lines.append("........")
        for row in g:
            lines.append("." + row.replace("#", "o") + "..")
        lines.append("")
    lines.append("map 0 0")
    lines.append(" ".join(key(ch) for ch in CHARS))
    open(out, "w").write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
