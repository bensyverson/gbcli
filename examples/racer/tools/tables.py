"""Writes the scanline engine's precomputed tables: include/road_geometry.inc
(the constants from geometry.py) and src/road_tables.asm (the data):

  HillHorizon      per hill level, the first screen line the road reaches
  HillProfiles     per hill level, per line FIRST_LINE..143: the road strip
                   (depth) that line shows; 128 bytes a level, 128-aligned
  CurveProfiles    per curve magnitude 0-16, per line: a right bend's
                   sideways offset in pixels, growing with distance; 128
                   bytes each. A left bend negates it (src/road.asm)
  StripeRows0..31  per stripe phase (depth mod 32): for each strip, the BG
                   row to show, minus one (the engine subtracts the line's
                   table index, line - 1, to get SCY)
  StripePtrs       a pointer to each StripeRows table (three to a 256-byte
                   page, so adding a strip to a pointer never carries)
  DepthStrip       per depth 0-255: the strip an object at that depth sits
                   on, or $FF when it is below the screen (passed)
  StripSize        per strip: which pre-scaled frame (0 far .. 3 near) an
                   object there uses, or $FF when it is too far to draw
  LaneX            per lane (LANES), per strip: the lane's offset from the
                   road's center in pixels (signed)

Hills are faked by how fast the strip index falls per line, going up the
screen from the bottom: flat ground falls at a constant rate and reaches the
horizon on FLAT_HORIZON; a climb ahead slows the fall (the road rises into
the sky), a drop ahead speeds it (the road vanishes over a crest).

Run: python3 -I tools/tables.py (from anywhere).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import geometry as g  # noqa: E402

CLIMB_TOP = 40         # the horizon at the steepest climb (level LEVELS-1)
DROP_BOTTOM = 104      # the horizon at the steepest drop (level 0)
MIN_STEP = 0.18        # strips per line, at least (the steepest climb)


def target_horizon(level):
    """Horizons spread evenly: the steepest climb reaches near the top, the steepest drop low."""
    if level >= g.FLAT:
        return round(g.FLAT_HORIZON - (g.FLAT_HORIZON - CLIMB_TOP) * (level - g.FLAT) / (g.LEVELS - 1 - g.FLAT))
    return round(g.FLAT_HORIZON + (DROP_BOTTOM - g.FLAT_HORIZON) * (g.FLAT - level) / g.FLAT)


def hill_profile(level):
    """The profile whose horizon is closest to target_horizon(level), by bisecting its curvature."""
    want = target_horizon(level)
    lo, hi = -0.05, 0.05
    best = simulate(0.0)
    for _ in range(60):
        mid = (lo + hi) / 2
        h, p = simulate(mid)
        if abs(h - want) < abs(best[0] - want):
            best = (h, p)
        # A larger accel (strips falling faster going up) lowers the horizon (larger line).
        if h < want:
            lo = mid
        else:
            hi = mid
    return best


def simulate(accel):
    """Strip index per line FIRST_LINE..LAST_LINE (255 above the horizon)."""
    lines = g.LAST_LINE - g.FLAT_HORIZON + 1
    step = g.ROWS / lines  # strips per line on flat ground
    r = g.ROWS - 1e-6
    prof = {}
    horizon = g.FIRST_LINE
    for y in range(g.LAST_LINE, g.FIRST_LINE - 1, -1):
        if r < 0:
            horizon = y + 1
            break
        prof[y] = int(r)
        r -= step
        step = max(MIN_STEP, step + accel)
    out = [prof.get(y, 255) for y in range(g.FIRST_LINE, g.LAST_LINE + 1)]
    return horizon, out


def curve_profile(m):
    """A right bend of magnitude m (0..FLAT); a left bend is its mirror."""
    k = m / g.FLAT * g.CURVE_MAX
    span = g.LAST_LINE - g.FLAT_HORIZON
    out = []
    for y in range(g.FIRST_LINE, g.LAST_LINE + 1):
        n = g.LAST_LINE - y
        v = round(k * (n / span) ** 2)
        out.append(max(-127, min(127, v)) & 0xFF)
    return out


def stripe_rows(phase):
    out = []
    for i in range(g.ROWS):
        band = ((g.depth(i) + phase) // g.STRIPE) & 1
        out.append(g.SKY_ROWS + band * g.ROWS + i - 1)
    return out


def depth_strip(z):
    """The strip whose depth is nearest z, or $FF below the screen."""
    if z == 0:
        return 0xFF
    i = round(g.Z_NUM / z - g.Z_OFF)
    if i >= g.ROWS:
        return 0xFF
    return max(0, i)


def strip_size(i):
    for frame, first in reversed(list(enumerate(g.SIZE_FROM))):
        if i >= first:
            return frame
    return 0xFF


def db(values):
    return "\tdb " + ", ".join(f"${v:02X}" for v in values)


def main():
    lines = [
        "; Generated by tools/tables.py from tools/geometry.py: do not edit; rerun it.",
        "",
        f"DEF SKY_ROWS EQU {g.SKY_ROWS}",
        f"DEF ROAD_ROWS EQU {g.ROWS}",
        f"DEF ROAD_MAP_ROWS EQU {g.MAP_ROWS}",
        f"DEF ROAD_SCX0 EQU {g.ROAD_SCX0}",
        f"DEF FIRST_LINE EQU {g.FIRST_LINE}",
        f"DEF PROFILE_LINES EQU {g.PROFILE_LINES}",
        f"DEF LEVELS EQU {g.LEVELS}",
        f"DEF FLAT EQU {g.FLAT}",
        f"DEF PHASES EQU {g.PHASES}",
    ]
    write("include", "road_geometry.inc", lines)
    lines = [
        "; Generated by tools/tables.py from tools/geometry.py: do not edit; rerun it.",
        "",
        'include "road_geometry.inc"',
        "",
        'SECTION "Hill horizons", ROMX',
        "HillHorizon::",
    ]
    profiles = []
    horizons = []
    for lvl in range(g.LEVELS):
        h, p = hill_profile(lvl)
        horizons.append(h)
        profiles.append(p)
    lines.append(db(horizons))
    lines += ["", 'SECTION "Hill profiles", ROM0, ALIGN[7]', "HillProfiles::"]
    for lvl, p in enumerate(profiles):
        lines.append(f"; level {lvl}: horizon on line {horizons[lvl]}")
        for k in range(0, len(p), 16):
            lines.append(db(p[k:k + 16]))
    lines += ["", 'SECTION "Curve profiles", ROM0, ALIGN[7]', "CurveProfiles::"]
    for m in range(g.FLAT + 1):
        p = curve_profile(m)
        lines.append(f"; magnitude {m}: levels FLAT + {m} and FLAT - {m}")
        for k in range(0, len(p), 16):
            lines.append(db(p[k:k + 16]))
    for page in range(0, g.PHASES, 3):
        lines += ["", f'SECTION "Stripe rows {page}", ROM0, ALIGN[8]']
        for ph in range(page, min(page + 3, g.PHASES)):
            lines += [f"StripeRows{ph}:", db(stripe_rows(ph))]
    lines += ["", 'SECTION "Object tables", ROMX', "DepthStrip::"]
    ds = [depth_strip(z) for z in range(256)]
    for k in range(0, 256, 16):
        lines.append(db(ds[k:k + 16]))
    lines.append("StripSize::")
    ss = [strip_size(i) for i in range(g.ROWS)]
    for k in range(0, g.ROWS, 16):
        lines.append(db(ss[k:k + 16]))
    lines.append("LaneX::")
    for lane, frac in enumerate(g.LANES):
        lines.append(f"; lane {lane}: {frac} half-widths from the center")
        lx = [round(frac * g.half_width(i)) & 0xFF for i in range(g.ROWS)]
        for k in range(0, g.ROWS, 16):
            lines.append(db(lx[k:k + 16]))
    lines += ["", 'SECTION "Stripe pointers", ROMX', "StripePtrs::"]
    lines.append("\tdw " + ", ".join(f"StripeRows{ph}" for ph in range(g.PHASES)))
    write("src", "road_tables.asm", lines)
    print(f"horizons by level: {horizons}")


def write(folder, name, lines):
    out = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", folder, name))
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"wrote {out}")


if __name__ == "__main__":
    main()
