#!/usr/bin/env python3
"""Writes the HUD font as pixel text, and the charmap that numbers it.

  python3 tools/gen_font.py [--check]

assets/tiles/font.pixels: one 8x8 tile per glyph, white (shade 0) on black
(shade 3), then the oil bar's nine tiles (0-8 columns full). `gbcli build`
turns it into FontTiles; the program loads them at tile FONT_BASE.
include/charmap.inc: a CHARMAP per glyph, so `db "KEYS"` writes tile numbers.
--check exits 1 if either file differs from what it would write.
"""

