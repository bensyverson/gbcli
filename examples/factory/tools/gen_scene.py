"""Turns art/scene.pixels into src/gen/scene.asm and include/gen/scene.inc.

    python3 tools/gen_scene.py          writes the files
    python3 tools/gen_scene.py --check  exits 1 if they are out of date

art/scene.pixels is a strip of 8x8 tiles; NAMES below names them in order,
and the include gives each its tile number (T_BLANK = 0, ...). The .asm
holds SceneTiles, in the game's color numbers (tools/tiles.py).
"""

import sys

import pixels
import tiles
import tuning

ART = tuning.PROJECT / "art" / "scene.pixels"
OUT_INC = tuning.PROJECT / "include" / "gen" / "scene.inc"
OUT_ASM = tuning.PROJECT / "src" / "gen" / "scene.asm"

NAMES = [
    "T_BLANK",        # white: the floor, the title and results screens
    "T_WALL",         # the HUD band's wall
    "T_RAIL",         # the wall's bottom row
    "T_BELT_TOP",     # a belt's top edge
    "T_BELT",         # a belt's surface, where pieces ride
    "T_BELT_BOTTOM",  # a belt's bottom edge
    "T_KEY_BG",       # the key column's panel
    "T_KEY_EDGE",     # the key column's left edge
    "T_BOX",          # 9 tiles: the score box, row by row
]
BOX_TILES = 9
HEADER = "; Generated by tools/gen_scene.py from art/scene.pixels. Do not edit."


def render():
    img = tiles.indexed(pixels.read(ART), where="art/scene.pixels")
    count = len(img[0]) // 8
    want = len(NAMES) - 1 + BOX_TILES
    if len(img) != 8 or count != want:
        sys.exit(f"art/scene.pixels: want {want * 8}x8 ({want} tiles), got {len(img[0])}x{len(img)}")
    inc = [HEADER, "IF !DEF(SCENE_INC)", "DEF SCENE_INC EQU 1"]
    inc += [f"DEF {name} EQU {i}" for i, name in enumerate(NAMES)]
    inc += [f"DEF SCENE_TILES EQU {count}", "ENDC"]
    asm = [HEADER, 'SECTION "Scene tiles", ROM0', "SceneTiles::"]
    for i, tile in enumerate(tiles.split(img, count, 1)):
        name = NAMES[min(i, len(NAMES) - 1)]
        asm.append("\tdb " + ",".join(f"${b:02X}" for b in tiles.encode(tile)) + f"   ; {name}")
    asm.append("SceneTilesEnd::")
    return {OUT_INC: "\n".join(inc) + "\n", OUT_ASM: "\n".join(asm) + "\n"}


def main():
    for path, text in render().items():
        name = path.relative_to(tuning.PROJECT)
        if "--check" in sys.argv:
            if not path.exists() or path.read_text() != text:
                sys.exit(f"{name} is out of date: run tools/gen_scene.py")
            continue
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(text)
        print(f"wrote {name}")


if __name__ == "__main__":
    main()
