#!/usr/bin/env python3
"""Generates crates/protocol/src/marks/table.rs: gbcli's one mark table.

The table is every precomposed letter in Latin-1 Supplement (U+00C0-U+00FF)
and Latin Extended-A (U+0100-U+017F) whose canonical decomposition is one
base character and one combining mark, plus every hiragana and katakana
letter (U+3040-U+30FF) whose canonical decomposition is a kana base and
U+3099 COMBINING KATAKANA-HIRAGANA VOICED SOUND MARK or U+309A ...
SEMI-VOICED SOUND MARK; plus the singletons whose canonical form is one of
those letters (U+212B ANGSTROM SIGN is A with a ring), a row's base (U+212A
KELVIN SIGN is K) or a mark in the table's class (U+0341 is U+0301), and the
list of marks the rows use.

It lives in gbcli_protocol so that gbcli and its consumers read one table
(Ben's ruling, 2026-11-09): the font reader refuses a decomposed key the
table knows, naming its precomposed form (design
2026-11-09-pixel-fonts-design.md, ruling 3); font composition builds a
missing letter from its base and mark; LoadHigh composes the string
literals' pairs with it. What it composes is a base followed by one mark
from its scope, left to right, after mapping the singletons, with no
canonical reordering (it holds no combining classes): NFC for those
sequences, not for every string.

Python's unicodedata is the reference, so neither needs a normalization
dependency at run time. Run from anywhere:

    python3 -I scripts/fonts/gen_marks.py          # rewrite table.rs
    python3 -I scripts/fonts/gen_marks.py --check  # fail if table.rs is stale
"""

import sys
import unicodedata
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
OUTPUT = REPO / "crates/protocol/src/marks/table.rs"
# (first, last, the marks a letter's decomposition may end in; None: any).
RANGES = [
    (0x00C0, 0x00FF, None),
    (0x0100, 0x017F, None),
    (0x3040, 0x30FF, {0x3099, 0x309A}),
]
# rustfmt's limit, so `cargo fmt` leaves the file be.
WIDTH = 100


def rows():
    for lo, hi, marks in RANGES:
        for cp in range(lo, hi + 1):
            d = unicodedata.decomposition(chr(cp))
            if not d or d.startswith("<"):
                continue
            parts = [int(p, 16) for p in d.split()]
            if len(parts) != 2 or not unicodedata.combining(chr(parts[1])):
                continue
            if marks is not None and parts[1] not in marks:
                continue
            base, mark = parts
            # A composition exclusion would decompose but never compose.
            pair = chr(base) + chr(mark)
            if unicodedata.normalize("NFC", pair) != chr(cp):
                sys.exit(f"U+{cp:04X} is excluded from composition")
            yield base, mark, cp


def is_combining_mark(cp):
    """gbcli_protocol::marks::is_combining_mark: the class the table holds."""
    return 0x0300 <= cp <= 0x036F or cp in (0x3099, 0x309A)


def singletons(table):
    """Every character whose canonical decomposition is one character that
    is a table letter, a row's base, or a mark in the table's class: NFC
    replaces it by that target (U+212A KELVIN SIGN is K, U+0341 is U+0301),
    so a string must map it before its pairs compose."""
    letters = {cp for _, _, cp in table}
    bases = {b for b, _, _ in table}
    for cp in range(0x110000):
        if 0xD800 <= cp <= 0xDFFF:
            continue
        d = unicodedata.decomposition(chr(cp))
        if not d or d.startswith("<") or " " in d:
            continue
        target = int(d, 16)
        if cp in letters or cp in bases:
            continue
        if target in letters or target in bases or is_combining_mark(target):
            yield cp, target


def u(cp):
    return f"'\\u{{{cp:04X}}}'"


def array(head, items):
    """`head = &[items];` as rustfmt writes it: on one line when it fits,
    else one item a line."""
    one_line = f"{head} = &[" + ", ".join(items) + "];"
    if len(one_line) <= WIDTH:
        return [one_line]
    return [f"{head} = &["] + [f"    {i}," for i in items] + ["];"]


def render():
    table = list(rows())
    marks = sorted({mark for _, mark, _ in table})
    lines = [
        "// Generated by scripts/fonts/gen_marks.py from Python's unicodedata "
        f"{unicodedata.unidata_version}; do not edit.",
        "",
        "use super::{Decomposition, Singleton, alias, row};",
        "",
        "/// Every (base, combining mark, precomposed letter) the table knows, by",
        "/// letter.",
    ]
    lines += array(
        "pub const DECOMPOSITIONS: &[Decomposition]",
        [f"row({u(b)}, {u(m)}, {u(cp)})" for b, m, cp in table],
    )
    lines += [
        "",
        "/// Every singleton and what it is canonically: a table letter, a row's",
        "/// base, or a mark in the table's class.",
    ]
    lines += array(
        "pub const SINGLETONS: &[Singleton]",
        [f"alias({u(cp)}, {u(t)})" for cp, t in singletons(table)],
    )
    lines += [
        "",
        "/// Every combining mark the table's rows use, in code point order.",
        # rustfmt packs an array of short items several to a line, by rules
        # this script would have to copy; one a line is easier to diff.
        "#[rustfmt::skip]",
    ]
    lines += array("pub const MARKS: &[char]", [u(m) for m in marks])
    return "\n".join(lines) + "\n"


def main():
    text = render()
    if "--check" in sys.argv[1:]:
        if not OUTPUT.exists() or OUTPUT.read_text() != text:
            sys.exit(f"{OUTPUT} is stale: run scripts/fonts/gen_marks.py")
        return
    OUTPUT.parent.mkdir(parents=True, exist_ok=True)
    OUTPUT.write_text(text)


if __name__ == "__main__":
    main()
