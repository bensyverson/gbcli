"""Writes assets/palettes.txt (the dmg line from colors.py) and checks that
every color lands on the shade colors.py expects (by nearest RGB; gbcli's
own rule may weigh channels differently, so the build's preview images are
the final word).

Run: python3 -I tools/palettes.py (from anywhere).
"""

import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import colors  # noqa: E402


def main():
    bad = []
    for name, want in colors.EXPECTED.items():
        got = colors.shade(getattr(colors, name))
        if got != want:
            bad.append(f"{name} lands on shade {got}, not {want}")
    out = os.path.normpath(os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "assets", "palettes.txt"))
    with open(out, "w") as f:
        f.write("# Generated by tools/palettes.py from tools/colors.py: the DMG shades of the\n")
        f.write("# project's colors. Each color takes its nearest entry's shade.\n")
        f.write("dmg: " + " ".join(colors.DMG_LINE) + "\n")
        f.write("road: " + " ".join(colors.ROAD_PALETTE) + "\n")
        f.write("title: " + " ".join(colors.TITLE_PALETTE) + "\n")
        f.write("bg/road.png = road\n")
        f.write("bg/title.png = title\n")
    print(f"wrote {out}")
    if bad:
        raise SystemExit("\n".join(bad))


if __name__ == "__main__":
    main()
