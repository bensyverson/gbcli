BLANK = "." * 16


def frames(rows):
    half_a = [BLANK] * 4 + rows[:8] + [BLANK] * 4
    half_b = [BLANK] * 4 + rows[8:] + [BLANK] * 4
    return [a + b + w for a, b, w in zip(half_a, half_b, rows)]


def text(toy, rows):
    for r in rows:
        assert len(r) == 16, (toy, r)
    return "\n".join([
        "format gbcli-pixels 1",
        f"# {toy}: placeholder art from tools/placeholder_toys.py.",
        "# Three 16x16 frames: half A, half B, the finished toy.",
        "size 48 16",
        "color . #ffffff",
        "color 1 #aaaaaa",
        "color 2 #555555",
        "color 3 #000000",
        "",
        "rows 0 0",
        *frames(rows),
        "",
    ])


def main():
    force = "--force" in sys.argv
    ART.mkdir(parents=True, exist_ok=True)
    for toy, rows in WHOLE.items():
        path = ART / f"{toy}.pixels"
        if path.exists() and not force:
            print(f"kept {path.relative_to(tuning.PROJECT)}")
            continue
        path.write_text(text(toy, rows))
        print(f"wrote {path.relative_to(tuning.PROJECT)}")


if __name__ == "__main__":
    main()
