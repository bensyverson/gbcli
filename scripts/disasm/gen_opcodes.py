#!/usr/bin/env python3
"""Generates crates/engine/src/disasm/table.rs from gbdev's opcode table.

Reads crates/engine/data/gb-opcodes/Opcodes.json (see SOURCE beside it) and
writes one Rust table entry per opcode, 256 base and 256 CB-prefixed. Run from
anywhere after updating the JSON:

    python3 -I scripts/disasm/gen_opcodes.py          # rewrite table.rs
    python3 -I scripts/disasm/gen_opcodes.py --check  # fail if table.rs is stale

Generating Rust keeps the engine free of a JSON parser at build or run time;
crates/engine/tests/it/disasm_table.rs checks the result against the JSON.
"""

import json
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
SOURCE = REPO / "crates/engine/data/gb-opcodes/Opcodes.json"
OUTPUT = REPO / "crates/engine/src/disasm/table.rs"

REGISTERS = {"A", "B", "C", "D", "E", "H", "L", "AF", "BC", "DE", "HL", "SP"}
CONDITIONS = {"NZ": "CondNz", "Z": "CondZ", "NC": "CondNc", "C": "CondC"}
IMMEDIATES = {"n8": "N8", "n16": "N16", "a8": "A8", "a16": "A16"}
BRANCHES = {"JP", "JR", "CALL", "RET"}


def kind(mnemonic, operands, i):
    name = operands[i]["name"]
    is_condition = mnemonic in BRANCHES and i == 0 and (mnemonic == "RET" or len(operands) == 2)
    if name in CONDITIONS and (name != "C" or is_condition):
        return "K::" + CONDITIONS[name]
    if name in REGISTERS:
        return "K::" + name.capitalize()
    if name in IMMEDIATES:
        return "K::" + IMMEDIATES[name]
    if name == "e8":
        return "K::Rel8" if mnemonic == "JR" else "K::E8"
    if name.startswith("$"):
        return f"K::Vector(0x{int(name[1:], 16):02X})"
    if name.isdigit():
        return f"K::Bit({name})"
    raise SystemExit(f"unknown operand {name!r} in {mnemonic}")


def entry(code, op, prefix_len):
    mnemonic = op["mnemonic"]
    variant = "Illegal" if mnemonic.startswith("ILLEGAL_") else mnemonic.capitalize()
    operand_bytes = sum(o.get("bytes", 0) for o in op["operands"])
    if prefix_len + operand_bytes != op["bytes"]:
        raise SystemExit(f"{code}: length {op['bytes']} != opcode + operand bytes")
    cycles = op["cycles"]
    not_taken = f"Some({cycles[1]})" if len(cycles) == 2 else "None"
    specs = ", ".join(
        f"sp({kind(mnemonic, op['operands'], i)}, {str(not o['immediate']).lower()}, "
        f"{str(o.get('increment', False)).lower()}, {str(o.get('decrement', False)).lower()})"
        for i, o in enumerate(op["operands"])
    )
    flags = "".join(op["flags"][f] for f in "ZNHC")
    return (
        f"    op(M::{variant}, {op['bytes']}, {cycles[0]}, {not_taken}, \"{flags}\", &[{specs}]), "
        f"// {code} {mnemonic}"
    )


def generate():
    table = json.loads(SOURCE.read_text())
    lines = [
        "// @generated by scripts/disasm/gen_opcodes.py from",
        "// crates/engine/data/gb-opcodes/Opcodes.json (gbdev/gb-opcodes, CC0-1.0). Do not edit.",
        "",
        "use super::types::{Mnemonic as M, OpInfo, OperandKind as K, op, sp};",
        "",
    ]
    for name, key, prefix_len in (("BASE", "unprefixed", 1), ("CB", "cbprefixed", 2)):
        lines.append("#[rustfmt::skip]")
        lines.append(f"pub(super) static {name}: [OpInfo; 256] = [")
        for code in range(256):
            hex_code = f"0x{code:02X}"
            lines.append(entry(hex_code, table[key][hex_code], prefix_len))
        lines.append("];")
        lines.append("")
    return "\n".join(lines)


def main():
    text = generate()
    if "--check" in sys.argv[1:]:
        if OUTPUT.read_text() != text:
            raise SystemExit(f"{OUTPUT} is stale; rerun {Path(__file__).name}")
        return
    OUTPUT.write_text(text)


if __name__ == "__main__":
    main()
